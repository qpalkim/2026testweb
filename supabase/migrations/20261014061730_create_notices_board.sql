create table public.notices (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) between 1 and 160),
  content text not null check (char_length(btrim(content)) between 1 and 12000),
  is_pinned boolean not null default false,
  created_at timestamptz not null default now()
);

create index notices_board_order_idx
  on public.notices (is_pinned desc, created_at desc);

alter table public.notices enable row level security;

grant select on public.notices to anon, authenticated;
grant insert, update, delete on public.notices to authenticated;
grant usage, select on sequence public.notices_id_seq to authenticated;

create policy "Anyone can read notices"
  on public.notices
  for select
  to anon, authenticated
  using (true);

create policy "Admins can create notices"
  on public.notices
  for insert
  to authenticated
  with check ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

create policy "Admins can update notices"
  on public.notices
  for update
  to authenticated
  using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

create policy "Admins can delete notices"
  on public.notices
  for delete
  to authenticated
  using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
